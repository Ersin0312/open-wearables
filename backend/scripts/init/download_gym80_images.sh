ok=0
skipped=0
failed=0

for entry in "${ENTRIES[@]}"; do
  name="${entry%%:*}"
  url="${entry#*:}"
  target="$TARGET_DIR/$name.webp"

  if [[ -f "$target" ]]; then
    skipped=$((skipped+1))
    continue
  fi

  if curl -fsSL -A "$UA" "$url" -o "$target.tmp" 2>/dev/null; then
    mv "$target.tmp" "$target"
    ok=$((ok+1))
    printf "✓ %s\n" "$name"
  else
    rm -f "$target.tmp"
    failed=$((failed+1))
    printf "✗ FAILED %s  (%s)\n" "$name" "$url"
  fi

  sleep 0.1
done

echo ""
echo "Done. $ok downloaded, $skipped already present, $failed failed."
